#!/usr/bin/env python3
"""fix_chrono_index.py — Fix known ordering issues in the chronological
theorem index generated by chrono_logger.

Problem: chrono_logger inserts checkpoint calls after every ;; boundary.
When multiple theorems are declared between two ;; (e.g. inside a
`module ... struct ... end;;` block), they are all captured in a single
checkpoint. The order within that checkpoint depends on the internal
order of !theorems (a cons-list), which does NOT match the source
declaration order.

Currently affected:
- thecops.ml: `module Hashek = struct ... end;;` contains 4 declarations
  (hashek_def, hashek_thm, hashek_prop, hashek_eq) without internal ;;.
  chrono_logger captures them in order thm, prop, eq, def instead of
  the correct source order def, thm, prop, eq.

Fix: reorder affected theorems to match source declaration order,
then renumber all positions sequentially.

Usage:
  python3 fix_chrono_index.py data/thm_index/theorem_index_chrono.jsonl
"""

import json
import sys


# ============================================================================
# Known ordering corrections
# ============================================================================

# Each entry: list of theorem names in correct source declaration order.
# These override whatever order chrono_logger produced.
CORRECTIONS = [
    # thecops.ml, module Hashek = struct ... end;;
    # Source order (lines 16-21): hashek_def, hashek_thm, hashek_prop, hashek_eq
    ["Hashek.hashek_def", "Hashek.hashek_thm",
     "Hashek.hashek_prop", "Hashek.hashek_eq"],
]


# ============================================================================
# Main
# ============================================================================

def main():
    if len(sys.argv) != 2:
        print("Usage: fix_chrono_index.py <theorem_index_chrono.jsonl>",
              file=sys.stderr)
        sys.exit(1)

    path = sys.argv[1]

    with open(path) as f:
        entries = [json.loads(line) for line in f if line.strip()]

    total_fixes = 0

    for correct_order in CORRECTIONS:
        # Find the entries that need reordering
        name_set = set(correct_order)
        indices = [i for i, e in enumerate(entries)
                   if e["thm_name"] in name_set]

        if len(indices) != len(correct_order):
            missing = name_set - {entries[i]["thm_name"] for i in indices}
            print(f"  WARNING: not all names found for correction "
                  f"{correct_order[0]}..., missing: {missing}",
                  file=sys.stderr)
            continue

        # Check they are consecutive
        expected_indices = list(range(min(indices), min(indices) + len(indices)))
        if indices != expected_indices:
            print(f"  WARNING: entries for {correct_order[0]}... are not "
                  f"consecutive (indices={indices}), skipping",
                  file=sys.stderr)
            continue

        # Check current order
        current_order = [entries[i]["thm_name"] for i in indices]
        if current_order == correct_order:
            print(f"  {correct_order[0]}...: already in correct order")
            continue

        # Reorder: place entries at the same indices but in correct order
        name_to_entry = {entries[i]["thm_name"]: entries[i] for i in indices}
        for j, name in enumerate(correct_order):
            entries[indices[j]] = name_to_entry[name]

        print(f"  Fixed: {current_order} -> {correct_order}")
        total_fixes += 1

    # Renumber positions sequentially
    if total_fixes > 0:
        for i, e in enumerate(entries):
            e["position"] = i

    # Write back
    with open(path, "w") as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")

    print(f"Done: {total_fixes} correction(s) applied, "
          f"{len(entries)} theorems total.")


if __name__ == "__main__":
    main()
